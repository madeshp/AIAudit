#!/usr/bin/env python3
"""
AI Audit Evaluation Agents — Reference Implementation (stateless)
==================================================================

Single-file, runnable implementation of the multi-agent system described in
"AI Audit Evaluation Agents — Python Multi-Agent Implementation Guide
(Azure OpenAI)".

This version is fully stateless: nothing is persisted anywhere. Every audit
check is computed on the fly from the FastAPI request payload and returned
directly in the response. There is no database, no file-based store, and no
server-side session state — call POST /audit/evaluate with an EvidenceBundle
and get an AuditRunReport back in the same request/response cycle.

What this file implements (guide section references in brackets):

  - Core data contracts: EvidenceBundle, AgentVerdict, AuditRunReport   [Sec 5]
  - Requirement-to-agent routing config, loaded from YAML if present,
    else falls back to the embedded routing table                     [Sec 2, 4.3]
  - Ingestion/normalization helpers for text docs                      [Phase 3]
  - A common Connector interface + Jira / GitLab / Datadog / Doc-store /
    IAM connectors (each degrades to a clearly-labeled mock/manual
    response if no credentials are configured, per the guide's
    "connector-failure -> Partial, never fabricate a Y" rule)          [Phase 4]
  - Azure OpenAI wrapper with JSON-mode structured output and schema
    validation + one retry. Falls back to a deterministic offline stub
    if no Azure OpenAI credentials are configured, so this file runs
    end-to-end with zero external deps.                                [Phase 5]
  - BaseAgent + 5 concrete agents (Log Evidence, Document,
    Compliance Registry, Jira/GitLab, Access)                          [Phase 6]
  - Orchestrator: config-driven routing + concurrent fan-out           [Phase 7]
  - Guardrails: citation grounding, schema/range validation,
    confidence gating, content-safety hook                             [Phase 8]
  - Aggregator: builds the AuditRunReport from the in-memory results,
    no storage involved                                                [Phase 9]
  - A stateless review/override transform endpoint (Phase 10's
    decision logic without a persisted audit trail — see note below)
  - FastAPI app exposing /health, /audit/evaluate, /audit/review
  - A CLI offline demo mode (`python ai_audit_agents.py demo`) that
    exercises the entire pipeline with mocked connectors and the
    offline LLM stub — no Azure/Jira/GitLab/Datadog credentials needed.

Note on persistence
--------------------
The guide's Phase 2 (persistence layer) and the audit-trail requirement
behind Requirement #1/#10 assume verdicts, LLM calls, and human overrides
are durably stored so an auditor can reconstruct "who submitted what, when,
and what the model said" after the fact. This version deliberately has none
of that: it is a pure request-in/response-out evaluator. If/when you need
an audit trail again, the natural seam is the `on_verdict` callback hook
threaded through `route_and_evaluate()` — wire it to whatever store you
choose (Postgres, Cosmos DB, a message queue, etc.) without touching the
agents, connectors, or orchestration logic.

Phases 11-13 (test suite/CI, security review, deployment/kill-switch
infra) are process and infrastructure concerns, not application code;
see the accompanying project scaffold (create_project.sh) for where
they land (tests/, infra/, .env.example).

Usage
-----
    python ai_audit_agents.py demo            # offline, no external services
    python ai_audit_agents.py serve           # run the FastAPI app (uvicorn)
    uvicorn ai_audit_agents:app --reload      # equivalent, dev-style

Configuration is via environment variables (see .env.example generated by
create_project.sh). Every external integration is optional: anything not
configured degrades to a mock/manual connector or the offline LLM stub
rather than crashing, so the system is always runnable.
"""

