def extract_text_from_ref(ref: str) -> str:
    """Best-effort text extraction for a document reference.

    Accepts a filesystem path (.txt/.md/.docx/.pdf) and extracts text with
    the appropriate library when available; any other string (URL, or a
    raw text snippet passed directly for demo/testing) is returned as-is.
    """
    path = Path(ref)
    try:
        if path.suffix.lower() in (".txt", ".md") and path.exists():
            return path.read_text(errors="ignore")
        if path.suffix.lower() == ".docx" and path.exists() and DocxDocument is not None:
            doc = DocxDocument(str(path))
            return "\n".join(p.text for p in doc.paragraphs)
        if path.suffix.lower() == ".pdf" and path.exists() and PdfReader is not None:
            reader = PdfReader(str(path))
            return "\n".join((p.extract_text() or "") for p in reader.pages)
    except Exception as exc:  # pragma: no cover
        log.warning("Failed to extract text from %s: %s", ref, exc)
        return f"[extraction failed for {ref}: {exc}]"
    # Not a recognized/existing file — treat as inline text or an opaque link.
    return ref


def validate_link(url: Optional[str]) -> bool:
    """Cheap well-formedness check; a real deployment also does a HEAD
    request per Phase 3 ('reject/flag broken links immediately')."""
    if not url:
        return False
    return bool(re.match(r"^https?://", url.strip()))


