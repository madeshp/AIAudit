def load_requirements_config() -> dict[int, dict[str, Any]]:
    """Load routing config from config/requirements.yaml if present,
    else fall back to the embedded table. Returns {req_id: entry}."""
    cfg_path = Path(os.getenv("REQUIREMENTS_CONFIG_PATH", "config/requirements.yaml"))
    entries = DEFAULT_REQUIREMENTS_CONFIG
    if cfg_path.exists() and yaml is not None:
        try:
            with cfg_path.open() as f:
                loaded = yaml.safe_load(f)
            if loaded:
                entries = loaded
                log.info("Loaded requirement routing config from %s", cfg_path)
        except Exception as exc:  # pragma: no cover
            log.warning("Failed to load %s (%s); using embedded defaults", cfg_path, exc)
    return {e["id"]: e for e in entries}


