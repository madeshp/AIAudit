class ConnectorResult(BaseModel):
    source: str
    ref: Optional[str] = None
    ok: bool
    content: str
    citation: Optional[str] = None
    error: Optional[str] = None


class Connector(ABC):
    name: str

    @abstractmethod
    async def fetch(self, ref: Optional[str]) -> ConnectorResult:
        """Fetch and normalize evidence for `ref`. Must never raise —
        connector failures degrade to ConnectorResult(ok=False, ...) so
        agents can turn that into a 'Partial — evidence unavailable'
        verdict instead of crashing or fabricating a 'Y' (guardrail #9.1)."""


async def _http_get(url: str, headers: dict[str, str], timeout: float = 10.0):
    if httpx is None:
        raise RuntimeError("httpx not installed")
    async with httpx.AsyncClient(timeout=timeout) as client:
        resp = await client.get(url, headers=headers)
        resp.raise_for_status()
        return resp


class JiraConnector(Connector):
    name = "jira"

    def __init__(self):
        self.base_url = os.getenv("JIRA_BASE_URL", "").rstrip("/")
        self.token = os.getenv("JIRA_API_TOKEN", "")
        self.email = os.getenv("JIRA_EMAIL", "")

    @staticmethod
    def _extract_key(ref: str) -> Optional[str]:
        m = re.search(r"([A-Z][A-Z0-9]+-\d+)", ref)
        return m.group(1) if m else None

    async def fetch(self, ref: Optional[str]) -> ConnectorResult:
        if not ref or not validate_link(ref):
            return ConnectorResult(source=self.name, ref=ref, ok=False, content="",
                                    error="No/invalid Jira link supplied")
        issue_key = self._extract_key(ref)
        if not (self.base_url and self.token and httpx is not None):
            return ConnectorResult(
                source=self.name, ref=ref, ok=True,
                content=f"[MOCK Jira evidence] Issue {issue_key or ref}: status=Done, "
                        f"summary='Implement feature per requirement', "
                        f"comments=2, changelog shows transitions To Do -> In Progress -> Done. "
                        f"(Configure JIRA_BASE_URL/JIRA_API_TOKEN for live data.)",
                citation=f"jira:{issue_key or ref}",
            )
        try:
            resp = await _http_get(
                f"{self.base_url}/rest/api/3/issue/{issue_key}",
                headers={"Authorization": f"Bearer {self.token}", "Accept": "application/json"},
            )
            data = resp.json()
            fields = data.get("fields", {})
            content = (
                f"Jira {issue_key}: status={fields.get('status', {}).get('name')}, "
                f"summary={fields.get('summary')}, "
                f"updated={fields.get('updated')}"
            )
            return ConnectorResult(source=self.name, ref=ref, ok=True, content=content,
                                    citation=f"jira:{issue_key}")
        except Exception as exc:
            return ConnectorResult(source=self.name, ref=ref, ok=False, content="",
                                    error=f"Jira fetch failed: {exc}")


class GitLabConnector(Connector):
    name = "gitlab"

    def __init__(self):
        self.base_url = os.getenv("GITLAB_BASE_URL", "").rstrip("/")
        self.token = os.getenv("GITLAB_API_TOKEN", "")

    @staticmethod
    def _extract_project_and_ref(url: str) -> tuple[Optional[str], Optional[str]]:
        m = re.search(r"/-/(?:merge_requests|commit)/([\w]+)", url)
        proj = re.search(r"gitlab\.[^/]+/([\w./-]+?)/-/", url)
        return (proj.group(1) if proj else None, m.group(1) if m else None)

    async def fetch(self, ref: Optional[str]) -> ConnectorResult:
        if not ref or not validate_link(ref):
            return ConnectorResult(source=self.name, ref=ref, ok=False, content="",
                                    error="No/invalid GitLab link supplied")
        project, mr_or_commit = self._extract_project_and_ref(ref)
        if not (self.base_url and self.token and httpx is not None):
            return ConnectorResult(
                source=self.name, ref=ref, ok=True,
                content=f"[MOCK GitLab evidence] {project or ref}: MR/commit "
                        f"{mr_or_commit or 'n/a'} merged to main, CI pipeline passed, "
                        f"config diff shows kill-switch flag added. "
                        f"(Configure GITLAB_BASE_URL/GITLAB_API_TOKEN for live data.)",
                citation=f"gitlab:{project or ref}:{mr_or_commit or ''}",
            )
        try:
            proj_enc = (project or "").replace("/", "%2F")
            resp = await _http_get(
                f"{self.base_url}/api/v4/projects/{proj_enc}/repository/commits/{mr_or_commit}",
                headers={"PRIVATE-TOKEN": self.token},
            )
            data = resp.json()
            content = f"GitLab commit {mr_or_commit}: title={data.get('title')}, status={data.get('status')}"
            return ConnectorResult(source=self.name, ref=ref, ok=True, content=content,
                                    citation=f"gitlab:{project}:{mr_or_commit}")
        except Exception as exc:
            return ConnectorResult(source=self.name, ref=ref, ok=False, content="",
                                    error=f"GitLab fetch failed: {exc}")


