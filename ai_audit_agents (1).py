class DocStoreConnector(Connector):
    """Fetches Confluence pages by link if configured, else operates on
    uploaded document text via extract_text_from_ref (Phase 3/4)."""

    name = "doc_store"

    def __init__(self):
        self.confluence_base = os.getenv("CONFLUENCE_BASE_URL", "")
        self.token = os.getenv("CONFLUENCE_API_TOKEN", "")

    async def fetch(self, ref: Optional[str]) -> ConnectorResult:
        if not ref:
            return ConnectorResult(source=self.name, ref=ref, ok=False, content="",
                                    error="No document/Confluence reference supplied")
        if validate_link(ref) and "confluence" in ref.lower():
            if not (self.confluence_base and self.token and httpx is not None):
                return ConnectorResult(
                    source=self.name, ref=ref, ok=True,
                    content=f"[MOCK Confluence evidence] Page at {ref}: contains design "
                            f"rationale, whitepaper sections 1-4. "
                            f"(Configure CONFLUENCE_BASE_URL/CONFLUENCE_API_TOKEN for live data.)",
                    citation=f"confluence:{ref}",
                )
            try:
                resp = await _http_get(ref, headers={"Authorization": f"Bearer {self.token}"})
                return ConnectorResult(source=self.name, ref=ref, ok=True,
                                        content=resp.text[:4000], citation=f"confluence:{ref}")
            except Exception as exc:
                return ConnectorResult(source=self.name, ref=ref, ok=False, content="",
                                        error=f"Confluence fetch failed: {exc}")
        # Otherwise treat as an uploaded document reference / inline text.
        text = extract_text_from_ref(ref)
        return ConnectorResult(source=self.name, ref=ref, ok=bool(text), content=text,
                                citation=f"doc:{ref}")


class IAMConnector(Connector):
    """Per the guide: if no IAM API exists yet, this is a manual-input
    adapter that still conforms to the Connector interface, so agents
    don't need special-casing once a real IAM API is wired in later."""

    name = "iam"

    def __init__(self):
        self.api_base = os.getenv("IAM_API_BASE_URL", "")
        self.token = os.getenv("IAM_API_TOKEN", "")

    async def fetch(self, ref: Optional[str]) -> ConnectorResult:
        if self.api_base and self.token and httpx is not None:
            try:
                resp = await _http_get(f"{self.api_base}/query?q={ref or ''}",
                                        headers={"Authorization": f"Bearer {self.token}"})
                return ConnectorResult(source=self.name, ref=ref, ok=True,
                                        content=resp.text[:2000], citation="iam:live-query")
            except Exception as exc:
                return ConnectorResult(source=self.name, ref=ref, ok=False, content="",
                                        error=f"IAM fetch failed: {exc}")
        # Manual-input adapter: the submitter's free-text answer *is* the evidence.
        content = ref or "[No IAM API configured and no user_input supplied]"
        return ConnectorResult(source=self.name, ref=ref, ok=bool(ref), content=content,
                                citation="iam:manual-input")


