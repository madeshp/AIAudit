class ComplianceStatus(str, Enum):
    YES = "Y"
    NO = "N"
    PARTIAL = "Partial"
    NOT_APPLICABLE = "N/A"


class EvidenceBundle(BaseModel):
    """Normalized payload the UI sends for one requirement or one run."""

    session_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    requirement_ids: list[int]
    user_input: Optional[str] = None
    document_refs: list[str] = Field(default_factory=list)
    screenshot_refs: list[str] = Field(default_factory=list)
    jira_link: Optional[str] = None
    gitlab_link: Optional[str] = None
    datadog_link: Optional[str] = None
    submitted_by: str = "unknown"
    submitted_at: datetime = Field(default_factory=utcnow)

    @field_validator("requirement_ids")
    @classmethod
    def _non_empty(cls, v: list[int]) -> list[int]:
        if not v:
            raise ValueError("requirement_ids must contain at least one id")
        return v


class AgentVerdict(BaseModel):
    """What every specialized agent returns — schema-enforced."""

    requirement_id: int
    agent_name: str
    compliance_status: ComplianceStatus
    rationale: str
    evidence_citations: list[str] = Field(default_factory=list)
    gaps: list[str] = Field(default_factory=list)
    confidence: float = Field(ge=0, le=1)
    model_name: str
    prompt_version: str
    flagged_for_human_review: bool = False
    evaluated_at: datetime = Field(default_factory=utcnow)


class AuditRunReport(BaseModel):
    session_id: str
    verdicts: list[AgentVerdict]
    overall_readiness_pct: float
    flagged_for_human_review: list[int]
    generated_at: datetime = Field(default_factory=utcnow)


class ReviewAction(str, Enum):
    APPROVE = "approve"
    OVERRIDE = "override"


class ReviewRequest(BaseModel):
    """Stateless review/override transform: the caller sends the verdict
    it received from /audit/evaluate back along with the reviewer's
    decision, and gets the updated verdict back. Nothing is stored here —
    persisting the resulting verdict (and who reviewed it) is the caller's
    responsibility if/when an audit trail is needed again."""

    verdict: AgentVerdict
    reviewer: str
    action: ReviewAction
    rationale: str
    override_status: Optional[ComplianceStatus] = None


