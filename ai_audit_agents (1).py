class BaseAgent(ABC):
    agent_name: str

    def __init__(self, llm: AzureOpenAIWrapper = LLM):
        self.llm = llm

    @abstractmethod
    async def gather_evidence(self, bundle: EvidenceBundle) -> tuple[str, list[str]]:
        """Call this agent's connectors and return (context_text, citation_ids)."""

    async def evaluate(self, bundle: EvidenceBundle, requirement_id: int) -> AgentVerdict:
        context, _citations = await self.gather_evidence(bundle)
        prompt = render_prompt(self.agent_name, requirement_id)
        verdict = await self.llm.evaluate(
            system_prompt=prompt,
            evidence_context=context,
            requirement_id=requirement_id,
            agent_name=self.agent_name,
            prompt_version=PROMPT_VERSION,
            session_id=bundle.session_id,
        )
        return apply_guardrails(verdict, context)

    @staticmethod
    def _join(results: list[ConnectorResult]) -> str:
        parts = []
        for r in results:
            if r.ok:
                parts.append(f"[{r.citation or r.source}] {r.content}")
            else:
                parts.append(f"[{r.source}:unavailable] {r.error}")
        return "\n\n".join(parts)


class LogEvidenceAgent(BaseAgent):
    agent_name = "log_evidence"

    async def gather_evidence(self, bundle: EvidenceBundle) -> tuple[str, list[str]]:
        results = [await CONNECTORS["datadog"].fetch(bundle.datadog_link)]
        if bundle.screenshot_refs:
            for ref in bundle.screenshot_refs:
                results.append(ConnectorResult(source="screenshot", ref=ref, ok=True,
                                                content=f"[screenshot on file: {ref}]",
                                                citation=f"screenshot:{ref}"))
        return self._join(results), [r.citation for r in results if r.citation]


class DocumentAgent(BaseAgent):
    agent_name = "document"

    async def gather_evidence(self, bundle: EvidenceBundle) -> tuple[str, list[str]]:
        results: list[ConnectorResult] = []
        for ref in bundle.document_refs:
            results.append(await CONNECTORS["doc_store"].fetch(ref))
        if bundle.gitlab_link:
            results.append(await CONNECTORS["gitlab"].fetch(bundle.gitlab_link))
        if not results and bundle.user_input:
            results.append(ConnectorResult(source="user_input", ok=True,
                                            content=bundle.user_input, citation="user_input"))
        if not results:
            results.append(ConnectorResult(source="doc_store", ok=False, content="",
                                            error="No document_refs or GitLab link supplied"))
        return self._join(results), [r.citation for r in results if r.citation]


