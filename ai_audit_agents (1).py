AGENT_TIMEOUT_SECONDS = float(os.getenv("AGENT_TIMEOUT_SECONDS", "30"))

# Optional hook: if you later want to persist/stream verdicts as they
# complete (Phase 2's "persist as it completes" idea) without threading
# storage code through the agents/orchestrator, register a callback here.
# It receives (session_id, AgentVerdict) and is fired right after each
# verdict is computed. Left as a no-op by default — nothing is stored.
OnVerdictHook = Callable[[str, AgentVerdict], Awaitable[None]]


def resolve_agent_for_requirement(requirement_id: int) -> BaseAgent:
    entry = REQUIREMENTS.get(requirement_id)
    if not entry:
        raise KeyError(f"Unknown requirement_id {requirement_id} — not in routing config")
    agent_cls = AGENT_REGISTRY.get(entry["agent"])
    if not agent_cls:
        raise KeyError(f"No agent registered for '{entry['agent']}' (requirement {requirement_id})")
    return agent_cls()


async def _evaluate_one(
    bundle: EvidenceBundle, requirement_id: int, on_verdict: Optional[OnVerdictHook],
) -> AgentVerdict:
    try:
        agent = resolve_agent_for_requirement(requirement_id)
        verdict = await asyncio.wait_for(
            agent.evaluate(bundle, requirement_id), timeout=AGENT_TIMEOUT_SECONDS
        )
    except asyncio.TimeoutError:
        verdict = AgentVerdict(
            requirement_id=requirement_id, agent_name="orchestrator",
            compliance_status=ComplianceStatus.PARTIAL,
            rationale="Agent timed out before producing a verdict.",
            evidence_citations=[], gaps=["Agent timeout — evidence unavailable"],
            confidence=0.0, model_name=LLM.model_name, prompt_version=PROMPT_VERSION,
            flagged_for_human_review=True,
        )
    except Exception as exc:  # never let one bad requirement kill the whole run
        log.exception("Agent failed for requirement %s", requirement_id)
        verdict = AgentVerdict(
            requirement_id=requirement_id, agent_name="orchestrator",
            compliance_status=ComplianceStatus.PARTIAL,
            rationale=f"Agent raised an unexpected error: {exc}",
            evidence_citations=[], gaps=[f"Unhandled error: {exc}"],
            confidence=0.0, model_name=LLM.model_name, prompt_version=PROMPT_VERSION,
            flagged_for_human_review=True,
        )
    if on_verdict is not None:
        await on_verdict(bundle.session_id, verdict)
    return verdict


async def route_and_evaluate(
    bundle: EvidenceBundle, on_verdict: Optional[OnVerdictHook] = None,
) -> list[AgentVerdict]:
    """Runs every requested requirement concurrently and returns the
    resulting verdicts. Nothing is read from or written to any store —
    the EvidenceBundle in, list[AgentVerdict] out, is the entire contract."""
    tasks = [_evaluate_one(bundle, req_id, on_verdict) for req_id in bundle.requirement_ids]
    return await asyncio.gather(*tasks)


# ===========================================================================
# Phase 9 — Aggregator (built purely from the in-memory verdict list)
# ===========================================================================

def build_audit_report(session_id: str, verdicts: list[AgentVerdict]) -> AuditRunReport:
    if not verdicts:
        raise ValueError("Cannot build a report from an empty verdict list")
    flagged_ids = [v.requirement_id for v in verdicts if v.flagged_for_human_review]
    yes_count = sum(1 for v in verdicts if v.compliance_status == ComplianceStatus.YES)
    readiness = round(100.0 * yes_count / len(verdicts), 1)
    return AuditRunReport(
        session_id=session_id,
        verdicts=verdicts,
        overall_readiness_pct=readiness,
        flagged_for_human_review=flagged_ids,
    )


def apply_review(review: ReviewRequest) -> AgentVerdict:
    """Stateless review/override transform (Phase 10's decision logic,
    without a persisted audit trail). Takes the verdict the caller already
    has and returns the updated one; storing it is the caller's job."""
    verdict = review.verdict.model_copy(deep=True)
    if review.action == ReviewAction.APPROVE:
        verdict.flagged_for_human_review = False
        verdict.rationale = f"{verdict.rationale}\n[Approved by {review.reviewer}: {review.rationale}]"
    else:  # OVERRIDE
        if review.override_status is not None:
            verdict.compliance_status = review.override_status
        verdict.flagged_for_human_review = False
        verdict.rationale = f"[Reviewer override by {review.reviewer}] {review.rationale}"
    return verdict


