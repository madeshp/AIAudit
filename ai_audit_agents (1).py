CONFIDENCE_THRESHOLD = float(os.getenv("CONFIDENCE_THRESHOLD", "0.7"))


def verify_citations_grounded(verdict: AgentVerdict, context: str) -> AgentVerdict:
    """Programmatically confirm every citation exists in the evidence
    context supplied to that call; downgrade ungrounded 'Y' verdicts."""
    ungrounded = [c for c in verdict.evidence_citations if c and c not in context]
    if ungrounded:
        verdict.gaps = list(verdict.gaps) + [f"Ungrounded citation removed: {c}" for c in ungrounded]
        verdict.evidence_citations = [c for c in verdict.evidence_citations if c not in ungrounded]
        if verdict.compliance_status == ComplianceStatus.YES and not verdict.evidence_citations:
            verdict.compliance_status = ComplianceStatus.PARTIAL
            verdict.confidence = min(verdict.confidence, 0.5)
    return verdict


def needs_human_review(verdict: AgentVerdict) -> bool:
    """Confidence gating (Phase 8) + Requirement #10 self-application:
    Partial/N verdicts and anything under threshold are never auto-published."""
    return (
        verdict.confidence < CONFIDENCE_THRESHOLD
        or verdict.compliance_status in (ComplianceStatus.PARTIAL, ComplianceStatus.NO)
    )


def apply_guardrails(verdict: AgentVerdict, context: str) -> AgentVerdict:
    verdict = verify_citations_grounded(verdict, context)
    if not content_safety_scan(verdict.rationale):
        verdict.rationale = "[content redacted by safety scan]"
    verdict.flagged_for_human_review = needs_human_review(verdict)
    return verdict


