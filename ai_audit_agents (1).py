class AzureOpenAIWrapper:
    """Centralizes all LLM calls: logging (to stdout/logger only — nothing
    is persisted), retries, schema enforcement.

    Falls back to a deterministic offline stub when Azure OpenAI is not
    configured, so `evaluate()` always returns a schema-valid AgentVerdict
    and the whole system is runnable without live credentials.
    """

    def __init__(self):
        self.endpoint = os.getenv("AZURE_OPENAI_ENDPOINT", "")
        self.api_key = os.getenv("AZURE_OPENAI_API_KEY", "")
        self.api_version = os.getenv("AZURE_OPENAI_API_VERSION", "2024-06-01")
        self.deployment = os.getenv("AZURE_OPENAI_DEPLOYMENT", "")
        self.temperature = float(os.getenv("AZURE_OPENAI_TEMPERATURE", "0.1"))
        self.max_tokens = int(os.getenv("AZURE_OPENAI_MAX_TOKENS", "800"))
        self._client = None
        if self.endpoint and self.api_key and self.deployment and AsyncAzureOpenAI is not None:
            self._client = AsyncAzureOpenAI(
                azure_endpoint=self.endpoint,
                api_key=self.api_key,
                api_version=self.api_version,
            )
        else:
            log.warning(
                "Azure OpenAI not fully configured (endpoint/key/deployment) — "
                "using offline deterministic LLM stub. Set AZURE_OPENAI_* env "
                "vars to use the real model."
            )

    @property
    def model_name(self) -> str:
        return self.deployment or "offline-stub"

    async def evaluate(
        self,
        *,
        system_prompt: str,
        evidence_context: str,
        requirement_id: int,
        agent_name: str,
        prompt_version: str,
        session_id: str,
    ) -> AgentVerdict:
        started = time.monotonic()
        if self._client is not None:
            data = await self._call_azure(system_prompt, evidence_context, requirement_id)
        else:
            data = self._call_offline_stub(evidence_context, requirement_id)

        data.setdefault("requirement_id", requirement_id)
        data.setdefault("agent_name", agent_name)
        data.setdefault("model_name", self.model_name)
        data.setdefault("prompt_version", prompt_version)

        try:
            verdict = AgentVerdict(**data)
        except ValidationError as exc:
            log.warning("Schema validation failed for req %s (%s); retrying once: %s",
                        requirement_id, agent_name, exc)
            if self._client is not None:
                data = await self._call_azure(
                    system_prompt, evidence_context, requirement_id,
                    correction_hint=str(exc),
                )
            else:
                data = self._call_offline_stub(evidence_context, requirement_id)
            data.setdefault("requirement_id", requirement_id)
            data.setdefault("agent_name", agent_name)
            data.setdefault("model_name", self.model_name)
            data.setdefault("prompt_version", prompt_version)
            verdict = AgentVerdict(**data)  # let this raise if still invalid

        latency_ms = int((time.monotonic() - started) * 1000)
        log.info(
            "llm_call session=%s req=%s agent=%s model=%s latency_ms=%d mock=%s",
            session_id, requirement_id, agent_name, self.model_name, latency_ms,
            self._client is None,
        )
        return verdict

    async def _call_azure(
        self, system_prompt: str, evidence_context: str, requirement_id: int,
        correction_hint: Optional[str] = None,
    ) -> dict[str, Any]:
        schema_hint = (
            "Respond ONLY with a JSON object with keys: "
            "compliance_status (one of 'Y','N','Partial','N/A'), "
            "rationale (string), evidence_citations (array of strings), "
            "gaps (array of strings), confidence (number 0-1)."
        )
        user_msg = f"{schema_hint}\n\nEvidence context:\n{evidence_context}"
        if correction_hint:
            user_msg += f"\n\nYour previous response was invalid: {correction_hint}\nFix it."
        try:
            resp = await self._client.chat.completions.create(  # type: ignore[union-attr]
                model=self.deployment,
                temperature=self.temperature,
                max_tokens=self.max_tokens,
                response_format={"type": "json_object"},
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_msg},
                ],
            )
            content = resp.choices[0].message.content or "{}"
            return json.loads(content)
        except Exception as exc:
            log.error("Azure OpenAI call failed for req %s: %s", requirement_id, exc)
            return {
                "compliance_status": ComplianceStatus.PARTIAL.value,
                "rationale": f"LLM call failed ({exc}); evidence unavailable for automated review.",
                "evidence_citations": [],
                "gaps": ["LLM call failed — see server logs for details"],
                "confidence": 0.0,
            }

    @staticmethod
    def _call_offline_stub(evidence_context: str, requirement_id: int) -> dict[str, Any]:
        """Deterministic, dependency-free stand-in for the LLM so the whole
        pipeline is exercisable offline. Heuristic only — never use in
        production; it exists purely so `demo` mode works with zero infra."""
        lower = evidence_context.lower()
        no_evidence = (not evidence_context.strip()) or "unavailable" in lower or "failed" in lower or "no/invalid" in lower
        citation_matches = re.findall(r"\b(jira|gitlab|datadog|doc|confluence|iam):[\w./%-]+", evidence_context)
        citations = list(dict.fromkeys(citation_matches))[:3]

        if no_evidence:
            return {
                "compliance_status": ComplianceStatus.PARTIAL.value,
                "rationale": "No usable evidence was supplied or retrievable for this "
                             "requirement; cannot confirm compliance from available context.",
                "evidence_citations": [],
                "gaps": ["No evidence retrieved — connector unavailable or reference missing"],
                "confidence": 0.3,
            }
        return {
            "compliance_status": ComplianceStatus.YES.value,
            "rationale": (
                f"[offline-stub] Evidence context for requirement {requirement_id} contains "
                f"{len(evidence_context)} characters referencing "
                f"{', '.join(citations) if citations else 'the supplied sources'}, which "
                "appears to address the requirement. Replace this stub with a live Azure "
                "OpenAI deployment for real evaluation."
            ),
            "evidence_citations": citations,
            "gaps": [],
            "confidence": 0.6,
        }


